import assert from 'node:assert/strict';
import { motionPose, paintPixelMotion } from '../src/characters/pixelMotion.js';

const walking = { speed: 9.2, alive: true };
const a = motionPose(walking, 0.12, false);
const b = motionPose(walking, 0.42, false);
assert.ok(a.legs[0].x * b.legs[0].x < 0, 'steps alternate over time');
assert.ok(a.legs.some(leg => leg.y === 0), 'a foot remains planted');
assert.ok(a.legs.some(leg => leg.y < 0), 'the other foot lifts');
assert.deepEqual(motionPose(walking, 0.12, false), a, 'frozen clock freezes pose');
assert.deepEqual(motionPose(walking, 2, true), motionPose(walking, 8, true), 'reduced motion is static');
assert.ok(motionPose({ ...walking, airborne: true }, 1, false).legs.every(leg => leg.y < 0), 'jump tucks both feet');
assert.ok(motionPose({ ...walking, speed: 0 }, 1, false).legs.every(leg => leg.x === 0 && leg.y === 0), 'idle keeps neutral feet');
assert.ok(motionPose({ ...walking, braking: true }, 1, false).legs.every(leg => leg.y === 0), 'braking braces both feet');
assert.ok(motionPose({ ...walking, justLanded: .05 }, 1, false).legs.every(leg => leg.y === 0), 'landing plants both feet');
assert.ok(motionPose({ ...walking, airborne: true, alive: false }, 1, false).legs.every(leg => leg.y === 0), 'KO takes precedence over airborne pose');
const calls = [];
const clears = [];
const ctx = { drawImage: (...args) => calls.push(args), clearRect: (...args) => clears.push(args) };
paintPixelMotion(ctx, { width: 140, height: 160 }, 'chicken', 'corredora', a);
assert.ok(calls.length >= 3, 'body and both legs are composed independently');
assert.equal(clears.length, 2, 'only the two bounded leg areas are removed');
assert.ok(clears.every(([x, y, width]) => x > 0 && width < 70 && y >= 120), 'feet cuts preserve the outer body and cape');
const horizontalCalls = [];
const horizontalClears = [];
paintPixelMotion({ drawImage: (...args) => horizontalCalls.push(args), clearRect: (...args) => horizontalClears.push(args) }, { width: 140, height: 160 }, 'chicken', 'corredora', { legs: [{ x: 4, y: 0 }, { x: 0, y: 0 }] });
assert.equal(horizontalClears.length, 1, 'planted leg remains untouched');
assert.ok(horizontalCalls.slice(1).every(args => args[4] === args[8]), 'leg pixels retain their original height');
const firstBand = horizontalCalls[1];
assert.equal(firstBand[1], firstBand[5], 'hip starts at its source x');
assert.equal(firstBand[2], firstBand[6], 'hip starts at its source y');
const joint = horizontalCalls.at(-1);
assert.equal(joint[1], joint[5], 'joint restores original x');
assert.equal(joint[2], joint[6], 'joint restores original y');
assert.ok(joint[4] <= 8, 'joint overlay does not restore original toes');
console.log('PASS: alternate steps, planted foot, pause, reduced motion, jump, idle and composed legs.');
